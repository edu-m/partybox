#!/usr/bin/env python3
"""Render TTF fonts into a compact 4-bit-alpha C header for partybox.

Usage: genfont.py [ui|cards] OUT.h     (default set: ui)

Glyphs are trimmed to their ink bounding box and packed two pixels per byte.
Regenerate only when changing fonts/sizes; the output is committed.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIRS = ["/usr/share/fonts/noto", "/usr/share/fonts/TTF", "/usr/share/fonts/truetype/noto",
             "/usr/share/fonts/truetype/dejavu"]

def find(name):
    import os
    for d in FONT_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit(f"font not found: {name}")

REGULAR = find("NotoSans-Regular.ttf")
BOLD = find("NotoSans-Bold.ttf")
SYMBOLS = find("DejaVuSans.ttf")  # fallback for arrows etc.

ASCII = [chr(c) for c in range(32, 127)]
EXTRA = ["↑", "↓", "•", "·", "…", "↵", "×"]

RANKS = list("0123456789AJQK")
SUITS = ["\u2660", "\u2665", "\u2666", "\u2663"]  # spade heart diamond club


def ui(path):
    """UI text: ASCII first and in order (fast lookup), symbols from DejaVu."""
    return [(ASCII, path), (EXTRA, SYMBOLS)]


# set name -> [(C name, [(chars, ttf path), ...] -- metrics from the first, pixel size)]
SETS = {
    "ui": [
        ("font_small_1x", ui(REGULAR), 15),
        ("font_body_1x", ui(REGULAR), 19),
        ("font_title_1x", ui(BOLD), 34),
        ("font_small_2x", ui(REGULAR), 28),
        ("font_body_2x", ui(REGULAR), 36),
        ("font_title_2x", ui(BOLD), 64),
    ],
    "cards": [
        ("font_rank_1x", [(RANKS, BOLD)], 28),
        ("font_pip_1x", [(SUITS, SYMBOLS)], 22),
        ("font_suit_1x", [(SUITS, SYMBOLS)], 72),
        ("font_rank_2x", [(RANKS, BOLD)], 56),
        ("font_pip_2x", [(SUITS, SYMBOLS)], 44),
        ("font_suit_2x", [(SUITS, SYMBOLS)], 144),
    ],
}


def render(cname, segments, size, out):
    fonts = [(chars, ImageFont.truetype(path, size)) for chars, path in segments]
    ascent, descent = fonts[0][1].getmetrics()
    glyphs, nibbles = [], []
    for ch, f in ((ch, f) for chars, f in fonts for ch in chars):
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch, anchor="ls")  # relative to baseline origin
        w, h = max(r - l, 0), max(b - t, 0)
        off = len(nibbles)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            nibbles.extend((p + 8) // 17 for p in img.tobytes())
        # y offset is measured from the top of the line box (baseline = ascent)
        glyphs.append((ord(ch), w, h, l, ascent + t, adv, off))
    if len(nibbles) % 2:
        nibbles.append(0)
    data = bytes(nibbles[i] | (nibbles[i + 1] << 4) for i in range(0, len(nibbles), 2))

    out.append(f"static const uint8_t {cname}_data[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(x) for x in data[i:i + 32]) + ",")
    out.append("};")
    out.append(f"static const struct glyph {cname}_glyphs[{len(glyphs)}] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const struct font {cname} = {{ {ascent + descent}, {ascent}, "
               f"{len(glyphs)}, {cname}_glyphs, {cname}_data }};")
    out.append("")
    return len(data)


def main():
    args = sys.argv[1:]
    which = args.pop(0) if len(args) == 2 else "ui"
    if which not in SETS or len(args) != 1:
        sys.exit(__doc__)
    out = [
        "/* Generated by tools/genfont.py -- do not edit.",
        " * Glyphs rasterized from Noto Sans (SIL Open Font License 1.1) and",
        " * DejaVu Sans (Bitstream Vera license) for a few symbols. */",
        "#pragma once",
        '#include "gfx.h"',
        "",
    ]
    total = 0
    for name, segments, size in SETS[which]:
        total += render(name, segments, size, out)
    with open(args[0], "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {args[0]}: {total} bytes of glyph data")


if __name__ == "__main__":
    main()
